/**
 * Builds the user prompt injecting author instructions, course context, and source materials.
 */
export function buildTopicGenerationPrompt(input: GenerateTopicInput): string {
  const parts: string[] = [
    `Создайте исчерпывающую учебную тему по запросу: "${input.topicTitle}".`,
    `Уровень сложности: ${input.difficulty}.`,
  ];

  if (input.targetAudience) {
    parts.push(`Целевая аудитория: ${input.targetAudience}.`);
  }

  if (input.focusAreas) {
    parts.push(`Особое внимание уделите следующим аспектам:\n${input.focusAreas}`);
  }

  if (input.sourceMaterial) {
    parts.push(
      `Используйте в качестве опорного материала и конспекта следующий текст:\n"""\n${input.sourceMaterial}\n"""`
    );
  }

  parts.push(
    `Напоминание: Сгенерируйте ПОЛНЫЙ, БОЛЬШОЙ и ГЛУБОКИЙ лонгрид со всеми формулами KaTeX, диаграммой Mermaid, полным кодом, 5 разнотипными вопросами квиза и карточками SM-2. Верните ТОЛЬКО валидный JSON.`
  );

  return parts.join("\n\n");
}
